export type Language = "bn" | "en";

// Convert numbers to Bengali digits
export const toBanglaNumber = (num: number | string): string => {
  const bnDigits = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
  return num
    .toString()
    .replace(/[0-9]/g, (match) => bnDigits[parseInt(match, 10)]);
};

export const formatPrice = (val: number, lang: Language): string => {
  if (lang === "bn") {
    return `৳ ${toBanglaNumber(val)}`;
  }
  return `৳ ${val}`;
};

export const formatPercent = (val: number, lang: Language): string => {
  const sign = val > 0 ? "+" : "";
  const numStr = `${sign}${val}%`;
  return lang === "bn" ? toBanglaNumber(numStr) : numStr;
};

export const formatRange = (min: number, max: number, lang: Language): string => {
  if (lang === "bn") {
    return `~${toBanglaNumber(min)}% - ${toBanglaNumber(max)}%`;
  }
  return `~${min}% - ${max}%`;
};

